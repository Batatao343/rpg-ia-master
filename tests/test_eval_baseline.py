"""Versioned CI baseline of the deterministic evals (SPEC-380 R1).

The baseline is generated by CI (linux); `compare` against it on Windows exits 2 on
`platform` by construction. These tests only check what does not depend on the platform.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

from evals.core.governance import assert_run_matches_repository, validate_repository
from evals.core.runner import load_run, run_eval, write_run

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / "evals" / "baselines" / "deterministic.json"


def test_baseline_bate_com_a_regua_atual() -> None:
    """Changing a dataset, evaluator or registry without regenerating the baseline fails here."""
    baseline = load_run(BASELINE)
    assert_run_matches_repository(baseline.metadata, validate_repository(ROOT / "evals"))
    assert baseline.passed is True
    assert baseline.metadata.platform.startswith("linux-py3.13.")
    assert baseline.metadata.seed == 7
    assert any(r.suite == "cards_combat" for r in baseline.results)


def _compare(current: Path, baseline: Path) -> int:
    return subprocess.run(
        [sys.executable, "-m", "evals", "--root", str(ROOT), "compare"]
        + ["--current", str(current), "--baseline", str(baseline)],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
    ).returncode


def _local_run(tmp_path: Path) -> Path:
    result = run_eval(ROOT, suites={"cards_combat"}, run_id="baseline-probe")
    json_path, _ = write_run(result, tmp_path / "run")
    return json_path


def _edited_copy(source: Path, target: Path, edit) -> Path:
    payload = json.loads(source.read_text(encoding="utf-8"))
    edit(payload)
    target.write_text(json.dumps(payload), encoding="utf-8")
    return target


def test_compare_sai_0_contra_si_mesmo_1_em_regressao_e_2_em_regua_trocada(
    tmp_path: Path,
) -> None:
    """R1 needs no change in evals/core: `compare` is already fail-closed."""
    current = _local_run(tmp_path)
    baseline = tmp_path / "baseline.json"
    shutil.copy(current, baseline)
    assert _compare(current, baseline) == 0

    def lower_metric(payload: dict) -> None:
        payload["metric_values"]["state_transition_pass_rate"] = 0.5

    regressed = _edited_copy(current, tmp_path / "regressed.json", lower_metric)
    assert _compare(regressed, baseline) == 1

    def other_ruler(payload: dict) -> None:
        hashes = payload["metadata"]["dataset_hashes"]
        hashes[next(iter(hashes))] = "sha256:" + "0" * 64

    stale = _edited_copy(baseline, tmp_path / "stale.json", other_ruler)
    assert _compare(current, stale) == 2
