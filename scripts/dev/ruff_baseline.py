"""Regenerate ruff-baseline.toml: per-file ignores for lint debt that predates the
incremental Ruff gate (workspace improvement #10).

New files get every rule selected in pyproject.toml; a legacy file only keeps the
rule codes it violated when the baseline was taken. Fixing a file and rerunning
this script shrinks the baseline; it never grows unless you rerun it on new debt,
which review should reject.

    bash scripts/dev/py.sh scripts/dev/ruff_baseline.py          # rewrite
    bash scripts/dev/py.sh scripts/dev/ruff_baseline.py --check  # fail if stale
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = ROOT / "ruff-baseline.toml"
HEADER = (
    "# Generated by scripts/dev/ruff_baseline.py — do not edit by hand.\n"
    "# Legacy lint debt per file; new files get every rule in pyproject.toml.\n"
    "# Fix a file, rerun the script, and the entry shrinks or disappears.\n"
)


def render(debt: dict[str, set[str]]) -> str:
    lines = [HEADER, "[lint.per-file-ignores]"]
    for path in sorted(debt, key=str.casefold):
        codes = ", ".join(f'"{code}"' for code in sorted(debt[path]))
        lines.append(f'"{path}" = [{codes}]')
    return "\n".join(lines) + "\n"


def current_debt() -> dict[str, set[str]]:
    original = BASELINE.read_bytes() if BASELINE.exists() else None
    BASELINE.write_text(HEADER + "[lint.per-file-ignores]\n", encoding="utf-8")
    try:
        result = subprocess.run(
            [sys.executable, "-m", "ruff", "check", "--output-format", "json", "--exit-zero", "."],
            cwd=ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
    finally:
        if original is None:
            BASELINE.unlink()
        else:
            BASELINE.write_bytes(original)
    if result.returncode:
        raise SystemExit(result.stderr)
    debt: dict[str, set[str]] = defaultdict(set)
    for item in json.loads(result.stdout or "[]"):
        if item.get("code"):
            debt[Path(item["filename"]).resolve().relative_to(ROOT).as_posix()].add(item["code"])
    return debt


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = render(current_debt())
    if args.check:
        actual = BASELINE.read_text(encoding="utf-8") if BASELINE.exists() else ""
        if actual != expected:
            print("ruff-baseline.toml is stale; rerun scripts/dev/ruff_baseline.py")
            return 1
        print("ruff-baseline.toml is current")
        return 0
    BASELINE.write_bytes(expected.encode("utf-8"))
    print(f"{sum(1 for line in expected.splitlines() if line.startswith(chr(34)))} files in baseline")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
