"""Ruff baseline: per-file ignores (`ruff-baseline.toml`) + counts (`ruff-baseline-counts.json`).

New files get every rule selected in pyproject.toml; a legacy file only keeps the rule codes it
violated when the baseline was taken. SPEC-416 adds the per-(file, rule) violation count, so a
baselined file can no longer grow new violations of an already-ignored rule: the counts only shrink.

    bash scripts/dev/py.sh scripts/dev/ruff_baseline.py --check     # confere toml + contagens
    bash scripts/dev/py.sh scripts/dev/ruff_baseline.py --tighten   # só desce (depois de consertar)
    bash scripts/dev/py.sh scripts/dev/ruff_baseline.py             # regrava tudo (coordenador)

The measurement does not touch the toml on disk: it runs ruff with
`--config "lint.per-file-ignores = {}"` (the `extend-per-file-ignores` of pyproject stay).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASELINE = ROOT / "ruff-baseline.toml"
COUNTS = ROOT / "ruff-baseline-counts.json"
HEADER = (
    "# Generated by scripts/dev/ruff_baseline.py — do not edit by hand.\n"
    "# Legacy lint debt per file; new files get every rule in pyproject.toml.\n"
    "# Fix a file, rerun the script, and the entry shrinks or disappears.\n"
)
Counts = dict[str, dict[str, int]]


def render(debt: dict[str, set[str]]) -> str:
    lines = [HEADER, "[lint.per-file-ignores]"]
    for path in sorted(debt, key=str.casefold):
        codes = ", ".join(f'"{code}"' for code in sorted(debt[path]))
        lines.append(f'"{path}" = [{codes}]')
    return "\n".join(lines) + "\n"


def violation_counts() -> Counts:
    """Contagem por arquivo x regra com os `per-file-ignores` do toml zerados."""
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--exit-zero",
            "--output-format",
            "json",
            "--config",
            "lint.per-file-ignores = {}",
            ".",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    if result.returncode:
        raise SystemExit(result.stderr)
    counts: Counts = defaultdict(lambda: defaultdict(int))
    for item in json.loads(result.stdout or "[]"):
        if item.get("code"):
            rel = Path(item["filename"]).resolve().relative_to(ROOT).as_posix()
            counts[rel][item["code"]] += 1
    return {f: dict(c) for f, c in counts.items()}


def current_debt() -> dict[str, set[str]]:
    return {f: set(c) for f, c in violation_counts().items()}


def _pairs(counts: Counts) -> set[tuple[str, str]]:
    return {(f, c) for f, codes in counts.items() for c in codes}


def load_counts(path: Path | None = None) -> Counts:
    path = path or COUNTS
    if not path.is_file():
        return {}
    return json.loads(path.read_text(encoding="utf-8")).get("counts", {})


def write_counts(counts: Counts, path: Path | None = None) -> None:
    path = path or COUNTS
    ordered = {f: dict(sorted(counts[f].items())) for f in sorted(counts)}
    data = {
        "_doc": "Gerado por scripts/dev/ruff_baseline.py (SPEC-416). Só encolhe: --tighten desce, "
        "regravação sem flag sobe (coordenador, com motivo no commit). Nunca à mão.",
        "counts": ordered,
    }
    path.write_text(
        json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )


def toml_pairs(path: Path | None = None) -> set[tuple[str, str]]:
    path = path or BASELINE
    if not path.is_file():
        return set()
    table = tomllib.loads(path.read_text(encoding="utf-8"))["lint"]["per-file-ignores"]
    return {(f, c) for f, codes in table.items() for c in codes}


def problems(measured: Counts, recorded: Counts, in_toml: set[tuple[str, str]]) -> list[str]:
    found = []
    for file, codes in sorted(measured.items()):
        for code, n in sorted(codes.items()):
            old = recorded.get(file, {}).get(code)
            if old is None:
                found.append(f"par novo {file}×{code} ({n})")
            elif n > old:
                found.append(f"cresceu {file}×{code} {old} → {n}")
    for file, codes in sorted(recorded.items()):
        for code, old in sorted(codes.items()):
            n = measured.get(file, {}).get(code)
            if n is None:
                found.append(f"órfão {file}×{code}; rode --tighten")
            elif n < old:
                found.append(f"folgada {file}×{code} {old} → {n}; rode --tighten")
    if in_toml != _pairs(recorded):
        found.append("toml ≠ contagens; rode --tighten")
    return found


def tightened(measured: Counts, recorded: Counts) -> Counts:
    """min(registrado, medido) dos pares que ainda existem; pares zerados somem."""
    out: Counts = {}
    for file, codes in recorded.items():
        now = measured.get(file, {})
        kept = {c: min(old, now[c]) for c, old in codes.items() if c in now}
        if kept:
            out[file] = kept
    return out


def write_all(counts: Counts) -> int:
    write_counts(counts)
    BASELINE.write_bytes(render({f: set(c) for f, c in counts.items()}).encode("utf-8"))
    return len(counts)


def run_tighten(measured: Counts, recorded: Counts) -> int:
    blocked = [
        m
        for m in problems(measured, recorded, _pairs(recorded))
        if m.startswith(("par novo", "cresceu"))
    ]
    if blocked:
        print("\n".join(blocked))
        print("--tighten recusado: conserte o código ou peça a regravação ao coordenador.")
        return 1
    print(f"{write_all(tightened(measured, recorded))} files in baseline")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true")
    group.add_argument("--tighten", action="store_true")
    args = parser.parse_args(argv)
    measured = violation_counts()
    if args.tighten:
        return run_tighten(measured, load_counts())
    if args.check:
        found = problems(measured, load_counts(), toml_pairs())
        print("\n".join(found) if found else "ruff baseline is current")
        return 1 if found else 0
    print(f"{write_all(measured)} files in baseline")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
